def _chart_ccc(step4, lang) -> bytes | None:
    """Two-panel Cash Conversion Cycle chart.

    Top panel:  CCC line alone, scaled to its own range, data labels at each point.
    Bottom panel: Component decomposition (Receivable Days, Inventory Days, Payable Days).
    """
    try:
        plt = _mpl_setup()
        import numpy as np
    except ImportError:
        return None
    s = _S(lang)
    bs = _annual_only(step4.get("balance_sheet_series", []))
    has_data = any(r.get("receivable_days") is not None for r in bs)
    if not has_data or len(bs) < 2:
        return None

    periods = [_year(r.get("period")) for r in bs]
    x = np.arange(len(periods))
    ccc  = np.array([r.get("cash_conversion_cycle") for r in bs], dtype=float)
    recv = np.array([r.get("receivable_days") for r in bs], dtype=float)
    inv  = np.array([r.get("inventory_days") for r in bs], dtype=float)
    pay  = np.array([r.get("payable_days") for r in bs], dtype=float)

    fig, (ax1, ax2) = plt.subplots(
        nrows=2, sharex=True, figsize=(6.5, 4.2),
        gridspec_kw={"height_ratios": [3, 2.5], "hspace": 0.08},
    )
    fig.patch.set_facecolor("white")

    # Title + formula annotation
    fig.suptitle(s["chart_ccc"], fontsize=8, color="#0b1f3a", fontweight="bold", y=0.97)
    formula = "CCC = Receivable + Inventory \u2212 Payable"
    if lang == "pt-br":
        formula = "CCC = Recebíveis + Estoques \u2212 Fornecedores"
    fig.text(0.5, 0.93, formula, ha="center", fontsize=7, color="#475569",
             fontfamily="monospace", style="italic")

    # ── Top panel: Cash Conversion Cycle ─────────────────────────────────
    _base_ax(ax1)
    ax1.plot(x, ccc, color="#0b1f3a", linewidth=3, marker="o", markersize=5,
             markerfacecolor="#0b1f3a", markeredgecolor="white", markeredgewidth=1.2,
             zorder=5, linestyle="-")
    ax1.axhline(0, color="#94a3b8", lw=0.8, zorder=1)
    # Data labels at every point
    for i, v in enumerate(ccc):
        if np.isnan(v):
            continue
        va = "bottom" if i > 0 and v < ccc[i - 1] else "top"
        offset = -9 if va == "bottom" else 9
