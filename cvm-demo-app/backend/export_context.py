def _section_header(t: dict, step1: dict | None, company_name: str, lang: str) -> str:
    today = date.today().isoformat()
    periods = ""
    if step1:
        dr = step1.get("date_range", {})
        start = _year(dr.get("start", ""))
        end   = _year(dr.get("end", ""))
        if start and end:
            periods = f"{start}–{end}"

    lines = [
        f"# {t['title']} — {company_name}",
        "",
        f"{t['analysis_period']}: {periods}",
        f"{t['data_source']}: CVM Open Data Portal",
        f"{t['generated']}: {today}",
        "",
        "---",
        "",
    ]
    return "\n".join(lines)


