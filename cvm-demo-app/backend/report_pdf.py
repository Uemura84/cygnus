def _pdf_risk_level(score, lang: str = "en") -> str:
    """Return the risk level label using canonical thresholds (CRITICAL ≥ 95)."""
    if score is None:
        return ""
    try:
        f = float(score)
    except (TypeError, ValueError):
        return ""
    if f >= 95:
        key = "CRITICAL"
    elif f >= 70:
        key = "HIGH"
    elif f >= 40:
        key = "MEDIUM"
    else:
        key = "LOW"
    return (_RISK_LEVELS_PT if lang == "pt-br" else _RISK_LEVELS_EN)[key]


