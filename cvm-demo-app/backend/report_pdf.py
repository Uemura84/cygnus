    ax2.plot(x, inv, color=(46/255, 134/255, 193/255, 0.50), linewidth=1.5, marker="o", markersize=3.5,
             markerfacecolor="white", markeredgecolor=(46/255, 134/255, 193/255, 0.50), markeredgewidth=1,
             label=s["inventory_days"], linestyle="-")
    ax2.plot(x, pay, color="#c0392b", linewidth=1.5, marker="o", markersize=3.5,
             markerfacecolor="white", markeredgecolor="#c0392b", markeredgewidth=1,
             alpha=0.6, label=s["payable_days"], linestyle="-")
    ax2.axhline(0, color="#94a3b8", lw=0.8)
    ax2.set_xticks(x)
    ax2.set_xticklabels(periods, fontsize=7)
    ax2.set_ylabel("days" if lang != "pt-br" else "dias", fontsize=6.5, color="#475569")
