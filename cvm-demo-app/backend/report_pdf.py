def _year(period_str) -> str:
    s = str(period_str or "")
    return s[:4] if len(s) >= 4 else s


def _annual_only(series: list) -> list:
    annual = [r for r in series if r.get("granularity") in ("annual", "dfp", None)]
    return annual if annual else series


def _fmt(v, decimals: int = 1, pct: bool = False, suffix: str = "") -> str:
    if v is None:
        return "—"
    try:
        val = f"{float(v):,.{decimals}f}"
        if pct:
            return val + "%"
        return val + suffix
    except (TypeError, ValueError):
        return "—"


def _fmt_brl_b(v) -> str:
    if v is None:
        return "—"
    try:
        b = float(v) / 1_000_000
        sign = "−" if b < 0 else ""
        return f"{sign}{abs(b):,.1f}"
    except (TypeError, ValueError):
        return "—"


def _risk_score_str(v) -> str:
    if v is None:
        return "—"
    try:
        f = float(v)
        return str(int(f)) if f == int(f) else f"{f:.1f}"
    except (TypeError, ValueError):
        return str(v)


def _impact_str(raw) -> str:
    if raw is None:
        return "—"
    if isinstance(raw, dict):
        return raw.get("formatted") or str(raw.get("value_brl", "—"))
    return str(raw)


def _stmt_label(stmt_type: str, s: dict) -> str:
    return s.get(f"stmt_{stmt_type.lower()}", stmt_type.upper())


def _rl_esc(text) -> str:
    """Decode any HTML entities then re-escape for reportlab's XML parser.

    reportlab Paragraph is XML-based: literal & and < must be escaped.
    LLM output and metric labels may contain &amp; or raw & — normalise both.
    """
    s = _html.unescape(str(text or ""))
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


