def _L(lang: str) -> dict:
    return _LABELS.get(lang, _LABELS["en"])


def _fmt(v, decimals: int = 1) -> str:
    if v is None:
        return "—"
    try:
        f = float(v)
        return f"{f:,.{decimals}f}"
    except (TypeError, ValueError):
        return str(v)


def _fmt_brl_b(v) -> str:
    """Format a BRL value in thousands as 'R$ X.X B'."""
    if v is None:
        return "—"
    try:
        b = float(v) / 1_000_000
        return f"R$ {b:,.1f} B"
    except (TypeError, ValueError):
        return str(v)


def _impact_str(raw) -> str:
    """estimated_impact may be a dict {formatted: '~R$ 3.2 bi'} or a plain string."""
    if raw is None:
        return "—"
    if isinstance(raw, dict):
        return raw.get("formatted") or str(raw.get("value_brl", "—"))
    return str(raw)


def _year(period_str: str) -> str:
    if period_str and len(str(period_str)) >= 4:
        return str(period_str)[:4]
    return str(period_str)


def _annual_only(series: list) -> list:
    annual = [r for r in series if r.get("granularity") in ("annual", "dfp", None)]
    return annual if annual else series


def _mk_table(headers: list[str], rows: list[list[str]]) -> str:
    """Build a markdown table string."""
    sep = "| " + " | ".join(["---"] * len(headers)) + " |"
    header_row = "| " + " | ".join(headers) + " |"
    data_rows = ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join([header_row, sep] + data_rows)


