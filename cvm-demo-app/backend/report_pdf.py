def _chart_working_capital(step4, lang) -> bytes | None:
    """Two-panel Working Capital chart.

    Top panel:  Net WC line with negative-zone shading.
    Bottom panel: Component decomposition (AR + Inventory above zero, AP below).
    """
    try:
        plt = _mpl_setup()
        import numpy as np
    except ImportError:
        return None
    s = _S(lang)
    bs = _annual_only(step4.get("balance_sheet_series", []))
    wc_data = [r for r in bs if r.get("working_capital") is not None]
    if len(wc_data) < 2:
        return None

    ts = step4.get("time_series", [])

    periods = [_year(r.get("period")) for r in wc_data]
    x = np.arange(len(periods))

    # All values in BRL billions (CVM stores BRL thousands)
    wc   = np.array([r["working_capital"] / 1_000_000 for r in wc_data])
    ar   = np.array([(r.get("accounts_receivable") or 0) / 1_000_000 for r in wc_data])
    inv  = np.array([(r.get("inventories") or 0) / 1_000_000 for r in wc_data])
    ap   = np.array([(r.get("accounts_payable") or 0) / 1_000_000 for r in wc_data])

    # WC / Revenue header metric with prior-period comparison
    def _wc_rev_pct(year_idx):
        yr = periods[year_idx]
        rev_row = next((t for t in ts if _year(t.get("period")) == yr), None)
        rev = (rev_row or {}).get("revenue_abs")
        if rev and rev != 0:
            return wc[year_idx] / (rev / 1_000_000) * 100
        return None

    latest_pct = _wc_rev_pct(-1)
    prior_pct  = _wc_rev_pct(-3) if len(wc_data) >= 3 else _wc_rev_pct(-2) if len(wc_data) >= 2 else None
    prior_yr   = periods[-3] if len(periods) >= 3 else (periods[-2] if len(periods) >= 2 else None)

    # ── Figure: two vertically stacked panels, shared x-axis ─────────────
    fig, (ax1, ax2) = plt.subplots(
        nrows=2, sharex=True,
        figsize=(5.5, 4.0),
        gridspec_kw={"height_ratios": [3, 2], "hspace": 0.08},
    )
    fig.patch.set_facecolor("white")

    # Title + WC/Revenue subtitle
    title = s["chart_wc"]
    fig.suptitle(title, fontsize=8, color="#0b1f3a", fontweight="bold", y=0.97)
    if latest_pct is not None:
        sub_parts = [f"WC / Revenue: {latest_pct:+.1f}%"]
        if prior_pct is not None and prior_yr:
            sub_parts.append(f"(was {prior_pct:+.1f}% in {prior_yr})")
        fig.text(0.5, 0.93, "  ".join(sub_parts),
                 ha="center", fontsize=7.5, color="#475569",
                 fontfamily="monospace", fontweight="bold")

    # ── Top panel: Net WC line ───────────────────────────────────────────
    _base_ax(ax1)
    ax1.plot(x, wc, color="#0b1f3a", linewidth=3, marker="o", markersize=5,
             markerfacecolor="#0b1f3a", markeredgecolor="white", markeredgewidth=1.2,
             zorder=5)
    ax1.axhline(0, color="#94a3b8", lw=0.8, zorder=1)
    # Negative-zone shading
    ax1.fill_between(x, wc, 0, where=(wc < 0), color="#C0392B", alpha=0.08,
                     interpolate=True, zorder=2)
    # Data label on final point
    last_val = wc[-1]
    label_str = f"{last_val:+.1f}B" if abs(last_val) >= 1 else f"{last_val * 1000:+,.0f}M"
    va = "bottom" if last_val < 0 else "top"
    offset = -8 if last_val < 0 else 8
    ax1.annotate(label_str, (x[-1], last_val),
                 textcoords="offset points", xytext=(0, offset),
                 fontsize=7, fontweight="bold", color="#0b1f3a",
                 ha="center", va=va, fontfamily="monospace",
                 bbox=dict(boxstyle="round,pad=0.2", facecolor="white",
                           edgecolor="#e2e8f0", alpha=0.9))
    # Y-axis in BRL B
    ax1.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0f}B"))
    ax1.set_ylabel("Net WC (BRL B)" if lang != "pt-br" else "CG Líq. (BRL B)",
                   fontsize=6.5, color="#475569")

    # ── Bottom panel: Component decomposition (diverging bars) ───────────
    _base_ax(ax2)
    bar_w = 0.55
    ax2.bar(x, ar,  width=bar_w, color="#2E86C1", alpha=0.85,
            label="Receivables" if lang != "pt-br" else "Contas a Receber")
    ax2.bar(x, inv, width=bar_w, bottom=ar, color=(46/255, 134/255, 193/255, 0.50),
            label="Inventory" if lang != "pt-br" else "Estoques")
    ax2.bar(x, -ap, width=bar_w, color="#C0392B", alpha=0.65,
            label="Payables" if lang != "pt-br" else "Fornecedores")
    ax2.axhline(0, color="#94a3b8", lw=0.8)
    ax2.set_xticks(x)
    ax2.set_xticklabels(periods, fontsize=7)
    ax2.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0f}B"))
    ax2.set_ylabel("Components (BRL B)" if lang != "pt-br" else "Componentes (BRL B)",
                   fontsize=6.5, color="#475569")
    ax2.legend(fontsize=6, loc="lower left", framealpha=0.9, edgecolor="#e2e8f0")

    plt.tight_layout(pad=0.3, rect=[0, 0, 1, 0.92])
    return _fig_to_rl(fig, plt, "working_capital")


