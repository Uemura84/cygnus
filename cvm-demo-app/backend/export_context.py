def _section_auditor_assessment(t: dict, step5: dict | None, lang: str) -> str:
    """Auditor Assessment section for markdown export."""
    if not step5:
        return ""
    assess = step5.get("auditor_assessment") or {}
    if not assess.get("available") or not assess.get("opinions"):
        return ""

    is_pt = lang == "pt"
    title = "## Avaliação do Auditor\n\n" if is_pt else "## Auditor Assessment\n\n"
    lines = [title]

    opinions = assess.get("opinions", [])
    gc_detected = assess.get("going_concern_detected", False)
    gc_count    = assess.get("going_concern_count", 0)
    gc_total    = assess.get("total_reports", 0)
    gc_periods  = assess.get("going_concern_periods", [])

    if gc_detected:
        if is_pt:
            lines.append(
                f"⚠ **Ênfase em Continuidade Operacional** — O auditor incluiu ênfase em "
                f"continuidade operacional em {gc_count} de {gc_total} relatórios ({', '.join(str(p) for p in gc_periods)}).\n\n"
            )
        else:
            lines.append(
                f"⚠ **Going Concern Emphasis** — Auditor included going concern emphasis in "
                f"{gc_count} of {gc_total} reports ({', '.join(str(p) for p in gc_periods)}).\n\n"
            )

    _op_en = {"sem_ressalva": "Unqualified", "com_ressalva": "Qualified",
              "adverso": "Adverse", "abstencao": "Disclaimer", "unknown": "Unknown"}
    _op_pt = {"sem_ressalva": "Sem ressalva", "com_ressalva": "Com ressalva",
              "adverso": "Adverso", "abstencao": "Abstenção", "unknown": "Desconhecido"}
    op_lbl = _op_pt if is_pt else _op_en

    hdr_period = "Período" if is_pt else "Period"
    hdr_firm   = "Firma"   if is_pt else "Firm"
    hdr_opn    = "Opinião" if is_pt else "Opinion"
    hdr_gc     = "Continuidade" if is_pt else "Going Concern"
    hdr_km     = "Principais Assuntos" if is_pt else "Key Matters"

    lines.append(f"| {hdr_period} | {hdr_firm} | {hdr_opn} | {hdr_gc} | {hdr_km} |")
    lines.append("|--------|------|---------|---------------|-------------|")
    for op in opinions:
        year = str(op.get("period", ""))[:4] or str(op.get("year", ""))
        firm = op.get("auditor_firm", "Unknown")
        opn  = op_lbl.get(op.get("opinion_type", "unknown"), op.get("opinion_type", ""))
        gc   = ("⚠ " + ("Sim" if is_pt else "Yes")) if op.get("has_going_concern") else ("Não" if is_pt else "No")
        km   = ", ".join((op.get("key_audit_matters") or [])[:3]) or "—"
        lines.append(f"| {year} | {firm} | {opn} | {gc} | {km} |")

    lines.append("\n\n")
    return "".join(lines)


def _section_pattern_detection(t: dict, step6: dict | None) -> str:
    if not step6:
        return ""

    risk_score = step6.get("risk_score", "—")
    risk_level = step6.get("risk_level", "—")
    algorithms_run = step6.get("algorithms_run", "—")
    findings = step6.get("findings", [])

    lines = [
        f"## {t['pattern_detection']}",
        "",
        f"### {t['risk_assessment']}",
        f"- **{t['risk_score']}:** {risk_score}/100 ({risk_level})",
        f"- **{t['algorithms_run']}:** {algorithms_run}",
        f"- **{t['findings']}:** {len(findings)}",
        "",
    ]

    # Group findings by module
    modules = {
        "profitability":      (t["profitability_findings"], []),
        "balance_sheet":      (t["balance_sheet_findings"], []),
        "cash_flow":          (t["cash_flow_findings"], []),
        "value_distribution": (t["value_distribution_findings"], []),
        "equity":             (t["equity_findings"], []),
        "auditor":            (t.get("auditor_findings", "Auditor Findings"), []),
        "cross_module":       (t["cross_module_diagnoses"], []),
    }
    for f in findings:
        mod = (f.get("module") or "").lower().replace(" ", "_")
        if mod in modules:
            modules[mod][1].append(f)

    for mod_key, (mod_label, mod_findings) in modules.items():
        if not mod_findings:
            continue
        lines.append(f"### {mod_label}")
        lines.append("")
        for f in mod_findings:
            fid = f.get("id", "")
            pattern = f.get("pattern") or f.get("description", "")
            severity = f.get("severity", "")
            desc = f.get("description", "")
            impact = f.get("estimated_impact")
            signals = f.get("contributing_signals", [])

            lines.append(f"**{fid} — {pattern} ({severity})**")
            if desc and desc != pattern:
                lines.append(desc)
            if impact:
                lines.append(f"*{t['estimated_impact']}: {_impact_str(impact)}*")
            if signals:
                lines.append(f"*{t['contributing_signals']}: {', '.join(str(s) for s in signals)}*")
            lines.append("")

    lines += ["---", ""]
    return "\n".join(lines)


def _section_ai_analysis(t: dict, step7: dict | None) -> str:
    if not step7:
        return ""

    response_text = step7.get("response_text", "")
    if not response_text:
        return ""

    try:
        data = json.loads(response_text)
    except Exception:
        return ""

    macro = data.get("macro_context", {})
    modules = data.get("modules", {})

    lines = [f"## {t['ai_analysis']}", ""]

    # Macro context
    macro_text = macro.get("summary") or macro.get("context") or ""
    if isinstance(macro_text, str) and macro_text:
        lines.append(f"### {t['macro_context']}")
        lines.append("")
        lines.append(macro_text)
        lines.append("")

    # Hypotheses by module — using finding_groups structure
    lines.append(f"### {t['hypotheses_by_group']}")
    lines.append("")
    for mod_key in ("profitability", "balance_sheet", "cash_flow", "cross_module"):
        mod_data = modules.get(mod_key, {})
        if not mod_data:
            continue
        groups = mod_data.get("finding_groups", [])
        if not groups:
            continue
        lines.append(f"**{mod_key.replace('_', ' ').title()}**")
        lines.append("")
        for grp in groups[:3]:
            group_label = grp.get("group_label", "")
            top_h = grp.get("top_hypothesis", {})
            title = top_h.get("title", "")
            conf  = top_h.get("confidence", "")
            explanation = top_h.get("explanation", "")
            if title:
                lines.append(f"- **{group_label}**: {title} [{conf}]")
                if explanation:
                    lines.append(f"  - {explanation[:300]}")
        lines.append("")

    lines += ["---", ""]
    return "\n".join(lines)


def _section_executive_summary(t: dict, step8: dict | None) -> str:
    if not step8:
        return ""

    response_text = step8.get("response_text", "")
    if not response_text:
        return ""

    try:
        data = json.loads(response_text)
    except Exception:
        return ""

    exec_summary = data.get("executive_summary", "")
    key_findings = data.get("key_findings", [])
    next_step = data.get("next_step", "")
    suggested_questions = data.get("suggested_questions", [])

    lines = [f"## {t['executive_summary']}", ""]

    if exec_summary:
        lines.append(exec_summary)
        lines.append("")

    if key_findings:
        lines.append(f"### {t['key_findings_table']}")
        lines.append("")
        headers = ["#", t["finding"], t["severity"], t["evidence"]]
        rows = []
        for i, f in enumerate(key_findings, 1):
            finding_text = f.get("finding") or f.get("description", "")
            severity = f.get("severity", "")
            evidence = f.get("evidence", "")
            rows.append([str(i), finding_text, severity, evidence])
        lines.append(_mk_table(headers, rows))
        lines.append("")

    if next_step:
        lines.append(f"### {t['next_step']}")
        lines.append("")
        lines.append(next_step)
        lines.append("")

    if suggested_questions:
        lines.append(f"## {t['suggested_questions']}")
        lines.append("")
        for i, q in enumerate(suggested_questions, 1):
            lines.append(f"{i}. {q}")
        lines.append("")

    lines += ["---", ""]
    return "\n".join(lines)


def _footer(t: dict) -> str:
    return f"*{t['footer']}*\n*{t['disclaimer']}*\n"


