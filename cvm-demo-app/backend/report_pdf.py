def _make_logo_drawing(width: float = 180, height: float = 50):
    """Return a reportlab Drawing of the Cygnus logo mark + wordmark."""
    try:
        from reportlab.graphics.shapes import (
            Drawing, Ellipse, Circle, String, Group, Rect
        )
        from reportlab.lib import colors as rlc
    except ImportError:
        return None

    d = Drawing(width, height)

    # Scale so the mark fits in the height
    scale = height / 80.0  # SVG viewBox is 80 tall, mark centre at y=40

    cx = 28 * scale  # mark centre x (40 in SVG → scaled)
    cy = height / 2  # vertical centre

    navy = rlc.Color(*NAVY)
    light = rlc.Color(0.961, 0.969, 0.980)

    # Outer ellipses (stroke only, decreasing opacity = lighter)
    for rx, ry, sw, op in [
        (28 * scale, 9 * scale,  0.8, 0.10),
        (21 * scale, 7 * scale,  0.9, 0.18),
        (14 * scale, 4.8 * scale,1.1, 0.32),
    ]:
        e = Ellipse(cx, cy, rx, ry)
        e.fillColor   = None
        e.strokeColor = rlc.Color(NAVY[0], NAVY[1], NAVY[2], op)
        e.strokeWidth = sw
        d.add(e)

    # Inner disc
    c1 = Circle(cx, cy, 5.5 * scale)
    c1.fillColor   = navy
    c1.strokeColor = None
    d.add(c1)

    # Light inner dot
    c2 = Circle(cx, cy, 2.2 * scale)
    c2.fillColor   = light
    c2.strokeColor = None
    d.add(c2)

    # Wordmark — Helvetica Bold, uppercase, letter-spaced
    text_x = cx + 32 * scale
    text_y = cy - 7 * scale   # baseline offset
    wordmark = String(text_x, text_y, "CYGNUS")
    wordmark.fontName  = "Helvetica-Bold"
    wordmark.fontSize  = 14 * scale
    wordmark.fillColor = navy
    d.add(wordmark)

    return d


