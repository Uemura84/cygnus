# Chart helpers (matplotlib) — return Drawing (SVG) or bytes (PNG fallback)
# ---------------------------------------------------------------------------

def _mpl_setup():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    # Use font names in SVG (not outlined paths) so svglib can map them
    matplotlib.rcParams["svg.fonttype"] = "none"
    return plt


def _fig_to_rl(fig, plt, chart_name: str = ""):
    """Save a matplotlib figure as SVG and convert to a ReportLab Drawing.

    Falls back to a high-DPI PNG (as raw bytes) if SVG conversion fails.
    Callers must pass the result to img_el(), which handles both types.
    """
    # ── Try SVG path first ──────────────────────────────────────────────────
    try:
        svg_buf = io.BytesIO()
        fig.savefig(svg_buf, format="svg", bbox_inches="tight")
        svg_buf.seek(0)
        from svglib.svglib import svg2rlg
        drawing = svg2rlg(svg_buf)
        if drawing is not None:
            plt.close(fig)
            return drawing
        raise ValueError("svg2rlg returned None")
    except Exception as exc:
        import logging as _log
        _log.getLogger(__name__).warning(
            "Chart '%s' SVG→Drawing failed (%s); falling back to PNG", chart_name, exc
        )

    # ── PNG fallback ────────────────────────────────────────────────────────
    try:
        png_buf = io.BytesIO()
        fig.savefig(png_buf, format="png", dpi=300, bbox_inches="tight")
        plt.close(fig)
        png_buf.seek(0)
        return png_buf.read()
    except Exception:
        plt.close(fig)
        return None


# Keep old name as alias so any external callers still work
def _fig_to_bytes(fig, plt) -> bytes:
    return _fig_to_rl(fig, plt)


