def _section_metrics(t: dict, step4: dict | None) -> str:
    if not step4:
        return ""

    ts = _annual_only(step4.get("time_series", []))
    bs = _annual_only(step4.get("balance_sheet_series", []))
    cf = _annual_only(step4.get("cash_flow_series", []))

    if not ts:
        return ""

    periods = [_year(r.get("period", "")) for r in ts]

    lines = [f"## {t['key_financial_metrics']}", ""]

    # Profitability table
    lines.append(f"### {t['profitability_annual']}")
    lines.append("")
    prof_metrics = [
        (t["gross_margin"],   "Gross_Margin_pct",  1),
        (t["ebit_margin"],    "EBIT_Margin_pct",   1),
        (t["ebitda_margin"],  "EBITDA_Margin_pct", 1),
        (t["cogs_revenue"],   "COGS_pct_Revenue",  1),
        (t["sga_revenue"],    "SGA_pct_Revenue",   1),
    ]
    headers = [t["metric"]] + periods
    rows = []
    for label, key, dec in prof_metrics:
        row = [label] + [_fmt(r.get(key), dec) for r in ts]
        rows.append(row)
    lines.append(_mk_table(headers, rows))
    lines.append("")

    # Balance sheet table
    if bs:
        lines.append(f"### {t['balance_sheet_annual']}")
        lines.append("")
        bs_periods = [_year(r.get("period", "")) for r in bs]
        bs_headers = [t["metric"]] + bs_periods
        bs_metrics = [
            (t["current_ratio"],    "current_ratio",    2, False),
            (t["quick_ratio"],      "quick_ratio",      2, False),
            (t["net_debt"],         "net_debt",         1, True),
            (t["debt_ebitda"],      "debt_to_ebitda",   1, False),
            (t["return_on_assets"], "return_on_assets", 1, False),
            (t["return_on_equity"], "return_on_equity", 1, False),
        ]
        bs_rows = []
        for label, key, dec, is_brl in bs_metrics:
            row = [label] + [_fmt_brl_b(r.get(key)) if is_brl else _fmt(r.get(key), dec) for r in bs]
            bs_rows.append(row)
        lines.append(_mk_table(bs_headers, bs_rows))
        lines.append("")

    # Cash flow table
    if cf:
        lines.append(f"### {t['cash_flow_annual']}")
        lines.append("")
        cf_periods = [_year(r.get("period", "")) for r in cf]
        cf_headers = [t["metric"]] + cf_periods
        cf_metrics = [
            (t["operating_cash_flow"], "operating_cash_flow", 1, True),
            (t["free_cash_flow"],      "free_cash_flow",      1, True),
            (t["capex_revenue"],       "capex_to_revenue",    1, False),
            (t["ocf_net_income"],      "ocf_to_net_income",   2, False),
        ]
        cf_rows = []
        for label, key, dec, is_brl in cf_metrics:
            row = [label] + [_fmt_brl_b(r.get(key)) if is_brl else _fmt(r.get(key), dec) for r in cf]
            cf_rows.append(row)
        lines.append(_mk_table(cf_headers, cf_rows))
        lines.append("")

    lines += ["---", ""]
    return "\n".join(lines)


